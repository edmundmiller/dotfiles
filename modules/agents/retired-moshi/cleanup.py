"""Archive retired Moshi hooks without removing unrelated runtime settings."""

import json
import os
import shlex
import shutil
import sys
import tempfile
from pathlib import Path


GENERATED_MARKER = "// Auto-generated by moshi-hook. Update with care."
HOOK_FILES = (
    ".pi/agent/extensions/moshi-hooks.ts",
    ".pi/agent/hooks/post/moshi-hooks.ts",
    ".omp/agent/extensions/moshi-hooks.ts",
    ".omp/agent/hooks/post/moshi-hooks.ts",
    ".config/opencode/plugins/moshi-hooks.ts",
    ".config/opencode/opencode/plugins/moshi-hooks.ts",
    ".config/opencode2/plugins/moshi-hooks.ts",
    ".config/opencode2/opencode/plugins/moshi-hooks.ts",
)


def is_moshi_command(hook):
    if not isinstance(hook, dict) or hook.get("type") != "command":
        return False
    command = hook.get("command")
    if not isinstance(command, str):
        return False
    try:
        args = shlex.split(command)
    except ValueError:
        return False
    return (
        len(args) == 2
        and Path(args[0]).name == "moshi-hook"
        and args[1] in {"claude-hook", "codex-hook"}
    )


def prune_hooks(data):
    hooks = data.get("hooks")
    if not isinstance(hooks, dict):
        return False
    changed = False
    for event, entries in list(hooks.items()):
        if not isinstance(entries, list):
            continue
        kept = []
        for entry in entries:
            if not isinstance(entry, dict) or not isinstance(entry.get("hooks"), list):
                kept.append(entry)
                continue
            filtered = [hook for hook in entry["hooks"] if not is_moshi_command(hook)]
            if filtered == entry["hooks"]:
                kept.append(entry)
                continue
            changed = True
            if filtered:
                kept.append({**entry, "hooks": filtered})
        if kept:
            hooks[event] = kept
        elif entries:
            del hooks[event]
    return changed


def cleanup(home):
    backup_root = None

    def backup(path):
        nonlocal backup_root
        if backup_root is None:
            state = home / ".local/state/dotfiles/retired-moshi"
            state.mkdir(parents=True, exist_ok=True, mode=0o700)
            backup_root = Path(tempfile.mkdtemp(prefix="backup-", dir=state))
        target = backup_root / path.relative_to(home)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)

    for relative in HOOK_FILES:
        path = home / relative
        if not path.exists():
            continue
        if path.is_symlink() or not path.read_text().startswith(GENERATED_MARKER):
            print(f"warning: preserving unrecognized Moshi hook: {path}", file=sys.stderr)
            continue
        backup(path)
        path.unlink()
        print(f"Archived retired Moshi hook: {path}")

    for relative in (".claude/settings.json", ".codex/hooks.json"):
        path = home / relative
        if not path.exists():
            continue
        if path.is_symlink():
            print(f"warning: preserving managed settings symlink: {path}", file=sys.stderr)
            continue
        data = json.loads(path.read_text())
        if not prune_hooks(data):
            continue
        backup(path)
        fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}-")
        try:
            with os.fdopen(fd, "w") as stream:
                stream.write(json.dumps(data, indent=2) + "\n")
                os.fchmod(stream.fileno(), path.stat().st_mode & 0o777)
            os.replace(temporary, path)
        finally:
            Path(temporary).unlink(missing_ok=True)
        print(f"Removed retired Moshi commands: {path}")
    if backup_root:
        print(f"Moshi cleanup backups: {backup_root}")


if __name__ == "__main__":
    cleanup(Path(sys.argv[1]))
